var age = 22;
console.log(age);
console.log(typeof age); // number

var name = "Sri";
console.log(name);
console.log(typeof name); // string

//Boolean - represent true or false
var hasCompletedTask = false;
console.log(hasCompletedTask);
console.log(typeof hasCompletedTask); //boolean

//BingInt - used for large integer
var num1 = 987456123654789n;
console.log(typeof num1); // bigint

//Undefined - variable declared without value
var email; "sng@mail.com";
console.log(email);
console.log(typeof  email); //undefined

// Null - intentionally assigning no value
var middleName = null ;
console.log(middleName);
console.log(typeof middleName); // object


// BigInt addition
var num2 = 100n;
console.log(num1 + num2); // 9007199254741095n